"""Serene Seasons tags for the flora mods' biomes, from their own c: tags (biome_traits.json).

Serene Seasons ships tags for vanilla only and z-seasons-terralith covers Terralith. This writes the same for
Biomes O' Plenty, Wilder Wild and Terrestria: c:is_hot -> tropical_biomes (wet and dry seasons, no snow),
c:is_swamp -> lesser_color_change_biomes. Everything else gets the four temperate seasons by default.

usage: python3 season_tags.py TRAITS_JSON DATAPACK_DIR
"""
import json, os, sys
traits, out = sys.argv[1:3]
tr = json.load(open(traits))
MODS = ("biomesoplenty:", "wilderwild:", "terrestria:")
def has(t, k): return k in t or k + "/overworld" in t
tropical = sorted(b for b, v in tr.items() if b.startswith(MODS) and has(v["tags"], "c:is_hot"))
lesser = sorted(b for b, v in tr.items() if b.startswith(MODS) and "c:is_swamp" in v["tags"] and b not in tropical)
d = os.path.join(out, "data", "sereneseasons", "tags", "worldgen", "biome"); os.makedirs(d, exist_ok=True)
for name, ids in (("tropical_biomes", tropical), ("lesser_color_change_biomes", lesser)):
    json.dump({"replace": False, "values": [{"id": i, "required": False} for i in ids]}, open(os.path.join(d, name + ".json"), "w"), indent=4)
json.dump({"pack": {"description": "Teaches Serene Seasons about the flora mods' biomes (generated by elysium-atlas/bake/season_tags.py)",
                    "min_format": 88, "max_format": 107.1}}, open(os.path.join(out, "pack.mcmeta"), "w"), indent=4)
print(len(tropical), "tropical,", len(lesser), "lesser colour change")
